// Convert accepted imagegen outputs to game assets, preserving the originals.
import fs from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const metadataDirectory = path.resolve("docs/card-art-2026-10-10");
const outputDirectory = path.resolve("public/images/cards/painted-v1");
await fs.mkdir(outputDirectory, { recursive: true });
const files = (await fs.readdir(metadataDirectory)).filter(
  (name) =>
    name.endsWith(".json") &&
    name !== "catalog.json" &&
    name !== "coverage.json"
);
const entries = [];
for (const file of files) {
  const item = JSON.parse(
    await fs.readFile(path.join(metadataDirectory, file), "utf8")
  );
  if (!item.source || !item.id) continue;
  const metadataTime = (await fs.stat(path.join(metadataDirectory, file)))
    .mtimeMs;
  for (const [suffix, width] of [
    ["", 768],
    ["-thumb", 288],
    ["-full", 1536],
  ]) {
    const destination = path.join(outputDirectory, `${item.id}${suffix}.webp`);
    const outputTime = await fs
      .stat(destination)
      .then((stat) => stat.mtimeMs)
      .catch(() => 0);
    if (outputTime < metadataTime) {
      await sharp(item.source)
        .resize(width, Math.round((width * 2) / 3), { fit: "cover" })
        .webp({ quality: suffix === "-thumb" ? 78 : 84 })
        .toFile(destination);
    }
  }
  entries.push([item.id, `/images/cards/painted-v1/${item.id}.webp`]);
}
entries.sort(([a], [b]) => a.localeCompare(b));
await fs.writeFile(
  "src/lib/card-art.generated.ts",
  "// Generated by scripts/prepare-card-art.mjs from reviewed imagegen outputs.\nexport const PAINTED_CARD_IMAGES: Record<string, string> = " +
    JSON.stringify(Object.fromEntries(entries), null, 2) +
    ";\n"
);
const catalog = JSON.parse(
  await fs.readFile(path.join(metadataDirectory, "catalog.json"), "utf8")
);
const covered = new Set(entries.map(([id]) => id));
const coverage = {
  total: catalog.length,
  illustrated: covered.size,
  missing: catalog
    .filter((card) => !covered.has(card.id))
    .map((card) => card.id),
};
await fs.writeFile(
  path.join(metadataDirectory, "coverage.json"),
  JSON.stringify(coverage, null, 2) + "\n"
);
console.log(
  JSON.stringify({
    total: coverage.total,
    illustrated: coverage.illustrated,
    remaining: coverage.missing.length,
  })
);
