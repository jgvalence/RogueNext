import fs from "node:fs/promises";
import sharp from "sharp";
const root = "docs/enemy-art-2026-10-10",
  dest = "public/images/enemies/painted-v1";
const catalog = JSON.parse(await fs.readFile(`${root}/catalog.json`, "utf8"));
await fs.mkdir(dest, { recursive: true });
const mapping = {},
  missing = [];
for (const enemy of catalog) {
  if (enemy.reuseCard) {
    mapping[enemy.id] = `/images/cards/painted-v1/${enemy.reuseCard}.webp`;
    continue;
  }
  const metadata = await fs
    .readFile(`${root}/${enemy.id}.json`, "utf8")
    .then(JSON.parse)
    .catch(() => null);
  if (!metadata) {
    missing.push(enemy.id);
    continue;
  }
  const modified = (await fs.stat(`${root}/${enemy.id}.json`)).mtimeMs;
  for (const [suffix, width] of [
    ["", 768],
    ["-thumb", 288],
    ["-full", 1536],
  ]) {
    const target = `${dest}/${enemy.id}${suffix}.webp`;
    if (
      await fs
        .stat(target)
        .then((s) => s.mtimeMs >= modified)
        .catch(() => false)
    )
      continue;
    await sharp(metadata.source)
      .resize(width, Math.round((width * 2) / 3), { fit: "cover" })
      .webp({ quality: suffix === "-thumb" ? 78 : 84 })
      .toFile(target);
  }
  mapping[enemy.id] = `/images/enemies/painted-v1/${enemy.id}.webp`;
}
await fs.writeFile(
  "src/lib/enemy-art.generated.ts",
  "// Generated by scripts/prepare-enemy-art.mjs.\nexport const PAINTED_ENEMY_IMAGES: Record<string, string> = " +
    JSON.stringify(mapping, null, 2) +
    ";\n"
);
const report = {
  total: catalog.length,
  illustrated: Object.keys(mapping).length,
  reused: catalog.filter((e) => e.reuseCard).length,
  missing,
};
await fs.writeFile(
  `${root}/coverage.json`,
  JSON.stringify(report, null, 2) + "\n"
);
console.log(report);
